// Writes src/guy-rank.ts: where a guy's odds put him among every guy dealt
// today. Run after changing parts or weights: bun scripts/guy-rank-table.ts
import { resolve, DEAL_PREFIX } from '../src/resolve';
import { guyScore } from '../src/rarity';
import { hash } from '../src/hash';

const N = 1_000_000;
const logs = new Float64Array(N);
for (let i = 0; i < N; i++) {
  // Seeds as makeSeed shapes them today: twelve base-36 characters.
  const seed = DEAL_PREFIX + (hash('rank' + i).toString(36) + hash('table' + i).toString(36)).padStart(12, '0').slice(-12);
  logs[i] = guyScore(resolve(seed));
}
logs.sort();
// Points from the commonest to the rarest: [log10 of "one in", share of guys at least this rare].
const tops = [1, 0.9, 0.75, 0.6, 0.5, 0.4, 0.3, 0.25, 0.2, 0.15, 0.1, 0.075, 0.05, 0.03, 0.02, 0.01, 0.0075, 0.005, 0.003, 0.002, 0.001, 0.0005, 0.0002, 0.0001, 0.00005, 0.00002, 0.00001];
const rows = tops.map(top => [+logs[Math.min(N - 1, Math.floor((1 - top) * N))].toFixed(4), top]);
const src = `// Generated by scripts/guy-rank-table.ts from ${N.toLocaleString('en-US')} guys of the current deal. Do not edit by hand.
/** [a guy's \`guyScore\`, the share of guys scoring at least that], commonest first. */
export const GUY_RANK: [number, number][] = ${JSON.stringify(rows)};
`;
await Bun.write(new URL('../src/guy-rank.ts', import.meta.url), src);
console.log(rows.map(r => r.join(' ')).join('\n'));
